"""Build the counting hands (numbers game, count=fingers) from OpenMoji drawings into src/js/hands.js.

Usage:  python app/make_hands.py

1 = ☝ (261D), 2 = ✌ (270C) and 5 = 🖐 (1F590) are OpenMoji's own drawings. OpenMoji has no hand
for 3 or 4, so they are made from ✌: its folded ring finger (3), then also its little finger (4),
are replaced by raised fingers, fanned out a little more each and drawn in the same style (same
yellow, 2-unit black outline, round ends). 6 to 10 are two hands, put together in board.js.
OpenMoji: https://openmoji.org, CC BY-SA 4.0 (these changed drawings are shared under the same license).
"""
import math, pathlib, re, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
CDN = "https://cdn.jsdelivr.net/npm/openmoji@17.0.0/color/svg/"


def get(code: str) -> str:
    with urllib.request.urlopen(CDN + code + ".svg", timeout=30) as r:
        return r.read().decode("utf-8")


def inner(svg: str) -> str:
    """Only the drawing: no <svg> wrapper, no ids, no empty groups, no line breaks."""
    body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    body = re.sub(r'\s*id="[^"]*"', "", body)
    body = re.sub(r"\s+", " ", body)
    body = re.sub(r"<g\s*/>", "", body)
    return re.sub(r">\s+<", "><", body).strip()


f = lambda x: f"{x:.2f}".rstrip("0").rstrip(".")
P = lambda p: f"{f(p[0])} {f(p[1])}"


def finger(bx, by, length, deg, half):
    """A raised finger from base centre (bx, by), `length` long, leaning `deg` degrees left, `half` = half its width."""
    a = math.radians(deg)
    ux, uy, px, py = -math.sin(a), -math.cos(a), math.cos(a), -math.sin(a)     # up the finger, to its right
    tx, ty = bx + ux * length, by + uy * length
    pt = lambda cx, cy, s: (cx + px * half * s, cy + py * half * s)
    return dict(lt=pt(tx, ty, -1), rt=pt(tx, ty, 1), lb=pt(bx, by, -1), rb=pt(bx, by, 1), half=half)


def edge(p, q, y):
    """The point at height y on the straight edge p → q."""
    return (p[0] + (q[0] - p[0]) * (y - p[1]) / (q[1] - p[1]), y)


def three_and_four(v: str):
    paths = re.findall(r"<path[^>]*/>", v)
    skin, lines = paths[0], paths[1:]
    ring_folded, pinky_folded = lines[5], lines[6]          # the two folded fingers of ✌ (outlines)
    Y = "#fcea2b"
    L = 'fill="none" stroke="#000" stroke-linecap="round" stroke-linejoin="round" stroke-width="2"'
    ring, pinky = finger(28.2, 41, 28.5, 12, 3.6), finger(21.6, 45, 24.5, 21, 3.5)
    arc = lambda F: f"A{f(F['half'])} {f(F['half'])} 0 0 1 {P(F['rt'])}"
    fill = lambda F, low: f'<path fill="{Y}" d="M{P(F["lb"])}L{P(F["lt"])}{arc(F)}L{P(F["rb"])}L{P(low)}Z"/>'
    ring_r30, ring_l35 = edge(ring["rt"], ring["rb"], 30), edge(ring["lt"], ring["lb"], 35)
    pinky_r35, pinky_l40 = edge(pinky["rt"], pinky["rb"], 35), edge(pinky["lt"], pinky["lb"], 40)
    # Ring finger: up its left side, round tip, down its right side into the gap next to ✌'s middle finger.
    ring_line = lambda start: f'<path {L} d="M{P(start)}L{P(ring["lt"])}{arc(ring)}L{P(ring_r30)}Q31.7 34 33.74 30.04"/>'
    # Little finger: from the side of the palm up, round tip, down into the gap next to the ring finger.
    pinky_line = (f'<path {L} d="M18.53 52.1Q{f(pinky_l40[0] + 1)} 46 {P(pinky_l40)}L{P(pinky["lt"])}{arc(pinky)}'
                  f'L{P(pinky_r35)}Q{f((pinky_r35[0] + ring_l35[0]) / 2)} 38.5 {P(ring_l35)}"/>')
    # 3: the ring finger starts where it leaves the folded little finger.
    three = fill(ring, (24.5, 46)) + skin + ring_line(edge(ring["lt"], ring["lb"], 34.3)) + "".join(l for l in lines if l != ring_folded)
    four = (fill(ring, (24.5, 46)) + fill(pinky, (18.6, 52)) + skin + ring_line(ring_l35) + pinky_line
            + "".join(l for l in lines if l not in (ring_folded, pinky_folded)))
    return inner(f"<svg>{three}</svg>"), inner(f"<svg>{four}</svg>")


def main() -> int:
    v = get("270C")
    three, four = three_and_four(v)
    hands = {1: inner(get("261D")), 2: inner(v), 3: three, 4: four, 5: inner(get("1F590"))}
    js = ['"use strict";',
          "/* hands.js: GENERATED by app/make_hands.py (don't edit by hand). Counting hands for count=fingers,",
          "   each drawn in a 72×72 box: OpenMoji ☝ (1), ✌ (2), 🖐 (5); 3 and 4 are made from ✌.",
          "   OpenMoji (https://openmoji.org), CC BY-SA 4.0. */",
          "const HANDS = {"]
    js += [f"  {n}: '{body}'," for n, body in hands.items()]
    js += ["};", ""]
    out = ROOT / "src/js/hands.js"
    out.write_text("\n".join(js), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
